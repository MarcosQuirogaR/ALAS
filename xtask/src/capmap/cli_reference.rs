//! The command-line reference, generated from the help text the binary
//! prints (10G). The map records each help line with its flags and its
//! description; `cli-reference.md` is rendered from those entries, so the
//! reference cannot list a flag the parser's help does not print.

use super::sources::SourceFile;
use serde_json::{json, Value};

const HELP_FILE: &str = "crates/alas-app/src/cli/args.rs";

/// The option lines of `help_text()`: `{flags, description}` per option, in
/// the order printed. A line is `  <flags>  <description>`, the flags column
/// ending at the first run of two or more spaces.
pub fn cli_help(files: &[SourceFile]) -> Value {
    let Some(source) = files.iter().find(|f| f.path == HELP_FILE) else {
        return json!([]);
    };
    let mut lines = Vec::new();
    for item in &source.ast.items {
        if let syn::Item::Fn(function) = item {
            if function.sig.ident == "help_text" {
                let mut collector = HelpLines::default();
                syn::visit::Visit::visit_item_fn(&mut collector, function);
                lines = collector.lines;
            }
        }
    }
    let options: Vec<Value> = lines
        .iter()
        .filter(|line| line.trim_start().starts_with('-'))
        .map(|line| {
            let body = line.trim_start();
            // Two spaces end the flags column; a metavariable argument ends it
            // after its closing `>` when the help line uses one space.
            let split = body.find("  ").or_else(|| body.find('>').map(|at| at + 1));
            let (flags, description) = match split {
                Some(at) => (body[..at].trim(), body[at..].trim()),
                None => (body, ""),
            };
            json!({"flags": flags, "description": description})
        })
        .collect();
    json!(options)
}

/// Markdown of the reference, rendered from the map's `cli_help` entries.
pub fn markdown(map: &Value) -> String {
    let mut out = String::from(
        "# Command-line reference (generated)\n\n\
         Generated by `cargo xtask capability-map` from the help text in \
         `crates/alas-app/src/cli/args.rs`; do not edit by hand.\n\n\
         | Option | Description |\n|---|---|\n",
    );
    for option in map
        .get("cli_help")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        let flags = option.get("flags").and_then(Value::as_str).unwrap_or("");
        let description = option
            .get("description")
            .and_then(Value::as_str)
            .unwrap_or("");
        out.push_str(&format!(
            "| `{}` | {} |\n",
            flags.replace('|', "\\|"),
            description.replace('|', "\\|")
        ));
    }
    out
}

/// Collects the string literal of every `line("...")` call in `help_text`.
#[derive(Default)]
struct HelpLines {
    lines: Vec<String>,
}

impl<'ast> syn::visit::Visit<'ast> for HelpLines {
    fn visit_expr_call(&mut self, node: &'ast syn::ExprCall) {
        if let syn::Expr::Path(path) = node.func.as_ref() {
            if path.path.is_ident("line") {
                if let Some(syn::Expr::Lit(lit)) = node.args.first() {
                    if let syn::Lit::Str(text) = &lit.lit {
                        self.lines.push(text.value());
                    }
                }
            }
        }
        syn::visit::visit_expr_call(self, node);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn flags_and_descriptions_split_at_the_column_gap() {
        let map =
            json!({"cli_help": [{"flags": "-c, --config <PATH>", "description": "Load overlay"}]});
        let text = markdown(&map);
        assert!(text.contains("| `-c, --config <PATH>` | Load overlay |"));
    }
}

//! Markdown view of the capability map.

use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write;

fn text(value: &Value) -> &str {
    value.as_str().unwrap_or_default()
}

fn list(value: &Value) -> String {
    value
        .as_array()
        .map(|items| items.iter().map(text).collect::<Vec<_>>().join(", "))
        .unwrap_or_default()
}

fn cell(value: &str) -> String {
    value.replace('|', "/").replace('\n', " ")
}

pub fn markdown(map: &Value) -> String {
    let mut out = String::new();
    out.push_str(
        "# ALAS capability map\n\n\
         Generated by `cargo xtask capability-map` from the source tree. Do not edit; see\n\
         [README.md](README.md). The same data, with per-field detail, is in\n\
         `capability-map.json`.\n\n",
    );
    summary(&mut out, map);
    config(&mut out, map);
    stages(&mut out, map);
    figures(&mut out, map);
    tools(&mut out, map);
    pages(&mut out, map);
    cli(&mut out, map);
    addons(&mut out, map);
    file_types(&mut out, map);
    smoke(&mut out, map);
    out
}

fn count(map: &Value, key: &str) -> usize {
    map[key].as_array().map_or(0, Vec::len)
}

fn summary(out: &mut String, map: &Value) {
    let fields = map["config"]["fields"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut by_status: BTreeMap<&str, usize> = BTreeMap::new();
    for field in &fields {
        *by_status.entry(text(&field["status"])).or_default() += 1;
    }
    let _ = writeln!(out, "## Summary\n");
    let _ = writeln!(out, "| Family | Count |\n|---|---|");
    let _ = writeln!(out, "| Configuration fields | {} |", fields.len());
    let _ = writeln!(
        out,
        "| Pipeline stages | {} |",
        count(map, "pipeline_stages")
    );
    let _ = writeln!(out, "| Report figures | {} |", count(map, "report_figures"));
    let _ = writeln!(out, "| GUI pages | {} |", count(map, "gui_pages"));
    let _ = writeln!(out, "| CLI flags | {} |", count(map, "cli_flags"));
    let _ = writeln!(out, "| Smoke tests | {} |\n", count(map, "smoke_tests"));
    let statuses: Vec<String> = by_status.iter().map(|(k, v)| format!("{k} {v}")).collect();
    let _ = writeln!(out, "Field status: {}.\n", statuses.join(", "));
}

fn config(out: &mut String, map: &Value) {
    let _ = writeln!(out, "## Configuration schema\n");
    let _ = writeln!(out, "{}\n", text(&map["config"]["status_note"]));
    let mut groups: BTreeMap<String, Vec<&Value>> = BTreeMap::new();
    for field in map["config"]["fields"].as_array().into_iter().flatten() {
        let path = text(&field["path"]);
        let group = path.split('.').next().unwrap_or_default().to_owned();
        groups.entry(group).or_default().push(field);
    }
    for (group, fields) in groups {
        let _ = writeln!(out, "### `{group}` ({} fields)\n", fields.len());
        let _ = writeln!(
            out,
            "| Path | Unit | Level | Status | Read by | GUI |\n|---|---|---|---|---|---|"
        );
        for field in fields {
            let gui: Vec<String> = field["gui"]
                .as_array()
                .into_iter()
                .flatten()
                .map(|g| text(&g["page"]).to_owned())
                .collect();
            let mut status = text(&field["status"]).to_owned();
            if let Some(kind) = field["exemption"]["kind"].as_str() {
                let _ = write!(status, " ({kind})");
            }
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {}{} | {} | {} |",
                text(&field["path"]),
                cell(text(&field["unit"])),
                text(&field["level"]),
                status,
                if field["shared_name"].as_bool().unwrap_or(false) {
                    " *"
                } else {
                    ""
                },
                list(&field["readers"]["compute"]),
                gui.join(", ")
            );
        }
        out.push('\n');
    }
    let _ = writeln!(out, "`*` the field name is shared by more than one configuration struct, so the reader list may include a same-named field.\n");
}

fn stages(out: &mut String, map: &Value) {
    let _ = writeln!(out, "## Pipeline stages\n\n| Stage | Label |\n|---|---|");
    for stage in map["pipeline_stages"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "| {} | {} |",
            stage["stage"],
            cell(text(&stage["label"]))
        );
    }
    out.push('\n');
}

fn figures(out: &mut String, map: &Value) {
    let _ = writeln!(
        out,
        "## Report figures and plot-data export ids\n\n| Id | Title | Category | Table |\n|---|---|---|---|"
    );
    for figure in map["report_figures"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} |",
            text(&figure["id"]),
            cell(text(&figure["title"])),
            text(&figure["category"]),
            text(&figure["table"])
        );
    }
    out.push('\n');
}

fn tools(out: &mut String, map: &Value) {
    let tools = &map["external_tools"];
    let _ = writeln!(out, "## External tools\n");
    let _ = writeln!(out, "Source: `{}`.\n", text(&tools["source"]));
    let _ = writeln!(out, "Resolved per run (`RunEnvironment`):\n");
    for entry in tools["run_environment"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "- `{}`: {}",
            text(&entry["name"]),
            cell(text(&entry["doc"]))
        );
    }
    let _ = writeln!(out, "\nSaved preferences (`ToolPreferences`):\n");
    for entry in tools["preferences"].as_array().into_iter().flatten() {
        let _ = writeln!(out, "- `{}`", text(&entry["name"]));
    }
    let _ = writeln!(out, "\nEnvironment overrides:\n");
    for entry in tools["environment_variables"]
        .as_array()
        .into_iter()
        .flatten()
    {
        let _ = writeln!(
            out,
            "- `{}` ({})",
            text(&entry["name"]),
            list(&entry["files"])
        );
    }
    out.push('\n');
}

fn pages(out: &mut String, map: &Value) {
    let _ = writeln!(
        out,
        "## GUI pages\n\n| Id | Title | Kind | Group | Surface | Window |\n|---|---|---|---|---|---|"
    );
    for page in map["gui_pages"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} | {} |",
            text(&page["id"]),
            cell(text(&page["title"])),
            text(&page["kind"]),
            text(&page["group"]),
            text(&page["surface"]),
            text(&page["window"])
        );
    }
    out.push('\n');
}

fn cli(out: &mut String, map: &Value) {
    let _ = writeln!(out, "## CLI flags\n\n| Flags | Takes a value |\n|---|---|");
    for flag in map["cli_flags"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "| `{}` | {} |",
            list(&flag["flags"]).replace(", ", "`, `"),
            if flag["takes_value"].as_bool().unwrap_or(false) {
                "yes"
            } else {
                "no"
            }
        );
    }
    out.push('\n');
}

fn addons(out: &mut String, map: &Value) {
    let addons = &map["addons"];
    let _ = writeln!(out, "## Add-ons\n");
    let _ = writeln!(
        out,
        "Kinds: {}. Source: `{}`.\n",
        list(&addons["kinds"]),
        text(&addons["source"])
    );
    for key in addons["manifest_keys"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "- `{}`: {}",
            text(&key["key"]),
            cell(text(&key["doc"]))
        );
    }
    out.push('\n');
}

fn file_types(out: &mut String, map: &Value) {
    let _ = writeln!(
        out,
        "## File types\n\nConfiguration dialogs accept {}.\n\n| Extension | Named files | Examples |\n|---|---|---|",
        list(&map["file_types"]["config_dialog_filter"])
    );
    for entry in map["file_types"]["by_extension"]
        .as_array()
        .into_iter()
        .flatten()
    {
        let _ = writeln!(
            out,
            "| `.{}` | {} | {} |",
            text(&entry["extension"]),
            entry["named_files"],
            list(&entry["examples"])
        );
    }
    out.push('\n');
}

fn smoke(out: &mut String, map: &Value) {
    let _ = writeln!(
        out,
        "## Smoke tests\n\n| Family | Test | Crate |\n|---|---|---|"
    );
    for test in map["smoke_tests"].as_array().into_iter().flatten() {
        let _ = writeln!(
            out,
            "| {} | `{}` | {} |",
            text(&test["family"]),
            text(&test["test"]),
            text(&test["crate"])
        );
    }
}

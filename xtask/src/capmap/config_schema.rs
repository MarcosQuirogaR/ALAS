//! The versioned configuration JSON Schema (`alas.config.v1`), generated from
//! the same field inventory as the capability map (10S).
//!
//! Each leaf of `AlasConfig` becomes one property at its dotted path, typed
//! from the Rust type the inventory records. The inventory's `min` and `max`
//! strings become `minimum` and `maximum` where they parse as numbers. Types
//! the schema does not expand (enums, nested sections read as one value) are
//! left unconstrained and say so in `x-alas-type`, so no type is invented.
//! Objects reject unknown keys, matching `#[serde(deny_unknown_fields)]` on
//! `AlasConfig`.

use serde_json::{json, Map, Value};

/// Version of the schema, the `schema_version` of the configuration files.
pub const SCHEMA_VERSION: u64 = 1;

/// Build the schema from the capability map's `config.fields` inventory.
pub fn config_schema(map: &Value) -> Result<Value, String> {
    let fields = map
        .pointer("/config/fields")
        .and_then(Value::as_array)
        .ok_or("capability map has no config.fields")?;
    let mut root = Map::new();
    for field in fields {
        let path = field
            .get("path")
            .and_then(Value::as_str)
            .ok_or("config field without a path")?;
        insert(&mut root, path, leaf(field))?;
    }
    Ok(json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": format!("ALAS configuration (alas.config.v{SCHEMA_VERSION})"),
        "description": "Generated by `cargo xtask capability-map` from docs/architecture/capability-map.json. Each property is one AlasConfig field; x-alas carries the unit, level and hidden flag from the inventory.",
        "x-alas-schema": "alas.config",
        "x-alas-schema-version": SCHEMA_VERSION,
        "type": "object",
        "additionalProperties": false,
        "properties": Value::Object(root),
    }))
}

/// Place `schema` at the dotted `path`, creating object levels on the way.
fn insert(node: &mut Map<String, Value>, path: &str, schema: Value) -> Result<(), String> {
    let mut parts = path.split('.').peekable();
    let mut current = node;
    while let Some(part) = parts.next() {
        if parts.peek().is_none() {
            if current.contains_key(part) {
                return Err(format!("config schema: duplicate path {path}"));
            }
            current.insert(part.to_owned(), schema);
            return Ok(());
        }
        let entry = current.entry(part.to_owned()).or_insert_with(
            || json!({"type": "object", "additionalProperties": false, "properties": {}}),
        );
        let properties = entry
            .get_mut("properties")
            .and_then(Value::as_object_mut)
            .ok_or_else(|| format!("config schema: {path} is both a field and a section"))?;
        current = properties;
    }
    Err(format!("config schema: empty path {path}"))
}

fn leaf(field: &Value) -> Value {
    let ty = field.get("type").and_then(Value::as_str).unwrap_or("");
    let mut schema = type_schema(ty);
    let text = |key: &str| field.get(key).and_then(Value::as_str).unwrap_or("").trim();
    if let Some(help) = field
        .get("help")
        .and_then(Value::as_str)
        .filter(|h| !h.is_empty())
    {
        schema["description"] = json!(help);
    }
    if is_numeric(ty) {
        if let Ok(min) = text("min").parse::<f64>() {
            schema["minimum"] = json!(min);
        }
        if let Ok(max) = text("max").parse::<f64>() {
            schema["maximum"] = json!(max);
        }
    }
    schema["x-alas"] = json!({
        "label": text("label"),
        "unit": text("unit"),
        "level": text("level"),
        "hidden": field.get("hidden").and_then(Value::as_bool).unwrap_or(false),
        "status": text("status"),
        "type": ty,
    });
    schema
}

fn is_numeric(ty: &str) -> bool {
    matches!(
        ty.trim_start_matches("Option<").trim_end_matches('>'),
        "f64" | "i64" | "u32" | "usize"
    )
}

/// The JSON type for a Rust type name from the inventory. An `Option<T>` is
/// the type or null.
fn type_schema(ty: &str) -> Value {
    if let Some(inner) = ty.strip_prefix("Option<").and_then(|t| t.strip_suffix('>')) {
        let mut schema = type_schema(inner);
        if let Some(name) = schema
            .get("type")
            .and_then(Value::as_str)
            .map(str::to_owned)
        {
            schema["type"] = json!([name, "null"]);
        }
        return schema;
    }
    match ty {
        "f64" => json!({"type": "number"}),
        "i64" | "u32" | "usize" => json!({"type": "integer"}),
        "bool" => json!({"type": "boolean"}),
        "String" => json!({"type": "string"}),
        "Vec<f64>" => json!({"type": "array", "items": {"type": "number"}}),
        "Vec<i64>" => json!({"type": "array", "items": {"type": "integer"}}),
        "(f64,f64,f64)" => {
            json!({"type": "array", "items": {"type": "number"}, "minItems": 3, "maxItems": 3})
        }
        "Vec<(f64,f64)>" => {
            json!({"type": "array", "items": {"type": "array", "items": {"type": "number"}, "minItems": 2, "maxItems": 2}})
        }
        _ => json!({}),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dotted_paths_nest_and_options_admit_null() {
        let map = json!({"config": {"fields": [
            {"path": "requirements.cruise_mach", "type": "f64", "min": "0.5", "max": "", "help": "h", "unit": "", "label": "", "level": "routine", "hidden": false, "status": "computed"},
            {"path": "requirements.ceiling", "type": "Option<f64>", "min": "", "max": "", "unit": "m", "label": "", "level": "", "hidden": true, "status": ""}
        ]}});
        let schema = config_schema(&map).unwrap();
        let req = &schema["properties"]["requirements"];
        assert_eq!(req["additionalProperties"], json!(false));
        assert_eq!(req["properties"]["cruise_mach"]["type"], json!("number"));
        assert_eq!(req["properties"]["cruise_mach"]["minimum"], json!(0.5));
        assert!(req["properties"]["cruise_mach"].get("maximum").is_none());
        assert_eq!(
            req["properties"]["ceiling"]["type"],
            json!(["number", "null"])
        );
        assert_eq!(
            req["properties"]["ceiling"]["x-alas"]["hidden"],
            json!(true)
        );
    }

    #[test]
    fn a_field_and_a_section_at_one_path_is_refused() {
        let map = json!({"config": {"fields": [
            {"path": "a", "type": "f64"},
            {"path": "a.b", "type": "f64"}
        ]}});
        assert!(config_schema(&map).is_err());
    }
}
